function expandWithSynonyms(q) {
  let expanded = q;
  for (const [alias, canonical] of SYNONYM_GROUPS) {
    if (q.includes(normalize(alias))) {
      expanded += normalize(canonical);
    }
  }
  return expanded;
}

/**
 * 질문에 대해 지식베이스를 점수 기반으로 검색합니다.
 * 키워드가 길수록(=구체적일수록) 높은 점수를 부여해
 * 여러 주제가 걸릴 때 가장 적합한 항목이 선택되도록 합니다.
 * 동의어 확장을 함께 적용해 keys에 정확히 없는 표현도 최대한 찾아냅니다.
 */
export function searchKnowledge(question) {
  const base = normalize(question);
  if (!base) return [];
  const q = expandWithSynonyms(base);

  const scored = [];
  for (const entry of KNOWLEDGE) {
    let score = 0;
    let hit = 0;
    for (const key of entry.keys) {
      const k = normalize(key);
      if (k && q.includes(k)) {
        score += k.length >= 4 ? 5 : k.length >= 3 ? 3 : 2;
        hit += 1;
      }
    }
    if (hit > 0) {
      // 서로 다른 키워드가 여러 개 맞으면 가중치 추가
      score += (hit - 1) * 2;
      scored.push({ entry, score });
    }
  }
  scored.sort((a, b) => b.score - a.score);
  return scored;
}

/** 카테고리별 주제 목록 (도움말 출력용) */
export function topicGuide() {
  return CATEGORIES.map((c) => {
    const topics = KNOWLEDGE.filter((k) => k.cat === c.id).map((k) => k.topic);
    return `• ${c.name}: ${topics.join(", ")}`;
  }).join("\n");
}

